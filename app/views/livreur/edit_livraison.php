                                    // Step 1: Get livraison.id from URL
                                    $idLivraison = $_GET['id'];

                                    // Step 2: Query that joins livraison → commande → user
                                    $query = "
                                    SELECT 
                                        livraison.id AS livraisonId,
                                        commande.idCommande,
                                        commande.dateCommande,
                                        commande.adresseClient,
                                        user.nom,
                                        user.telephone,
                                        livraison.statut
                                    FROM livraison
                                    JOIN commande ON livraison.idCommande = commande.idCommande
                                    JOIN user ON commande.idClient = user.id
                                    WHERE livraison.id = :idLivraison
                                    ";

                                    $stmt = $conn->prepare($query);
                                    $stmt->bindParam(':idLivraison', $idLivraison, PDO::PARAM_INT);
                                    $stmt->execute();

                                    if ($stmt->rowCount() > 0) {
                                        $row = $stmt->fetch(PDO::FETCH_ASSOC);

                                        $statut = $row['statut'];
                                        $badgeClass = match ($statut) {
                                            'EN_ATTENTE' => 'badge badge-info-inverse',
                                            'EN_COURS' => 'badge badge-warning-inverse',
                                            'LIVREE' => 'badge badge-success-inverse',
                                            'ANNULEE' => 'badge badge-danger-inverse',
                                            default => 'badge badge-secondary'
                                        };

