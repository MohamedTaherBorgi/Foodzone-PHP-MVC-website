                                            <td><span class='{$badgeClass}'>{$row['statut']}</span></td>
                                            <td> 
                                                <a href='../app/controllers/UpdateLivraisonStatut.php?id={$row['livraisonId']}&statut=LIVREE' class='btn btn-icon btn-round btn-outline-success'><i class='ti ti-download'></i></a>
                                                <a href='../app/controllers/UpdateLivraisonStatut.php?id={$row['livraisonId']}&statut=EN_COURS' class='btn btn-icon btn-outline-primary btn-round'><i class='ti ti-pencil'></i></a>
                                                <a href='../app/controllers/UpdateLivraisonStatut.php?id={$row['livraisonId']}&statut=ANNULEE' class='btn btn-icon btn-outline-danger btn-round'><i class='ti ti-close'></i></a>
